<?php

declare(strict_types=1);

namespace Infocyph\PHPForge\Support;

/**
 * Publishes deterministic companion resources for a PHPForge knowledge base.
 *
 * @phpstan-import-type FileRecord from KnowledgeFileCatalog
 * @phpstan-import-type KnowledgeDocument from KnowledgeBase
 * @phpstan-import-type GraphNodeSummary from KnowledgeGraphAnalyzer
 * @phpstan-import-type GraphCommunity from KnowledgeGraphAnalyzer
 * @phpstan-import-type GraphBridge from KnowledgeGraphAnalyzer
 * @phpstan-import-type GraphHealth from KnowledgeGraphAnalyzer
 * @phpstan-type KnowledgeAnalysis array{schema:string,schema_version:int,fingerprint:string,node_count:int,edge_count:int,file_count:int,node_types:array<string,int>,relationships:array<string,int>,languages:array<string,int>,central_nodes:list<array{id:string,type:string,name:string,file:string,degree:int}>,node_communities:array<string,int>,communities:list<GraphCommunity>,god_nodes:list<GraphNodeSummary>,surprising_connections:list<GraphBridge>,suggested_questions:list<array{type:string,question:string,why:string}>,graph_health:GraphHealth,certainties:array<string,int>,resolutions:array<string,int>}
 */
final class KnowledgeArtifacts
{
    private const string HTML_MARKER = '<meta name="generator" content="PHPForge knowledgebase">';

    private const string REPORT_MARKER = '<!-- Generated by PHPForge knowledgebase. -->';

    public function assertWritable(string $knowledgePath): void
    {
        $this->assertWritableTargets($this->paths($knowledgePath));
    }

    /**
     * @param array<string, mixed> $document
     * @param list<FileRecord> $records
     * @return list<string>
     */
    public function publish(array $document, array $records, string $knowledgePath): array
    {
        /** @var KnowledgeDocument $document */
        $paths = $this->paths($knowledgePath);
        $this->assertWritableTargets($paths);
        $analysis = $this->analysis($document, $records);
        $manifest = $this->manifest($document, $records);
        $this->writeJson($paths['manifest'], $manifest);
        $this->writeJson($paths['analysis'], $analysis);
        $this->write($paths['report'], $this->report($document, $analysis));
        $this->write($paths['html'], $this->html($document, $analysis));

        return [$knowledgePath, ...array_values($paths)];
    }

    /**
     * @param array<string, mixed> $document
     * @param list<FileRecord> $records
     * @return KnowledgeAnalysis
     */
    private function analysis(array $document, array $records): array
    {
        /** @var KnowledgeDocument $document */
        $types = [];
        $relationships = [];
        $languages = [];
        $degrees = [];

        foreach ($document['nodes'] as $node) {
            $types[$node['type']] = ($types[$node['type']] ?? 0) + 1;
        }

        foreach ($document['edges'] as $edge) {
            $relationships[$edge['relation']] = ($relationships[$edge['relation']] ?? 0) + 1;
            $degrees[$edge['source']] = ($degrees[$edge['source']] ?? 0) + 1;
            $degrees[$edge['target']] = ($degrees[$edge['target']] ?? 0) + 1;
        }

        foreach ($records as $record) {
            $languages[$record['language']] = ($languages[$record['language']] ?? 0) + 1;
        }

        ksort($types);
        ksort($relationships);
        ksort($languages);
        $graphAnalysis = new KnowledgeGraphAnalyzer()->analyze($document);

        return [
            'schema' => 'phpforge.knowledge-analysis',
            'schema_version' => 2,
            'fingerprint' => $document['fingerprint'],
            'node_count' => count($document['nodes']),
            'edge_count' => count($document['edges']),
            'file_count' => count($records),
            'node_types' => $types,
            'relationships' => $relationships,
            'languages' => $languages,
            'central_nodes' => $this->centralNodes($document, $degrees),
            ...$graphAnalysis,
        ];
    }

    /** @param array<string, string> $paths */
    private function assertWritableTargets(array $paths): void
    {
        foreach ($paths as $type => $path) {
            if (!is_file($path)) {
                continue;
            }

            $contents = file_get_contents($path);
            $owned = match ($type) {
                'manifest' => $this->hasSchema($contents, 'phpforge.knowledge-manifest'),
                'analysis' => $this->hasSchema($contents, 'phpforge.knowledge-analysis'),
                'report' => is_string($contents) && str_starts_with($contents, self::REPORT_MARKER),
                'html' => is_string($contents) && str_contains($contents, self::HTML_MARKER),
                default => false,
            };

            if (!$owned) {
                throw new \RuntimeException(sprintf('Refusing to overwrite non-PHPForge artifact: %s', $path));
            }
        }
    }

    /**
     * @param array<string, mixed> $document
     * @param array<string, int> $degrees
     * @return list<array{id:string,type:string,name:string,file:string,degree:int}>
     */
    private function centralNodes(array $document, array $degrees): array
    {
        /** @var KnowledgeDocument $document */
        $nodes = [];

        foreach ($document['nodes'] as $node) {
            if (!$node['defined']) {
                continue;
            }

            $nodes[] = [
                'id' => $node['id'],
                'type' => $node['type'],
                'name' => $node['name'],
                'file' => $node['file'],
                'degree' => $degrees[$node['id']] ?? 0,
            ];
        }

        usort($nodes, static fn(array $left, array $right): int => $right['degree'] <=> $left['degree'] ?: $left['id'] <=> $right['id']);

        return array_slice($nodes, 0, 20);
    }

    private function hasSchema(string|false $contents, string $schema): bool
    {
        if (!is_string($contents)) {
            return false;
        }

        try {
            $decoded = json_decode($contents, true, 32, JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            return false;
        }

        return is_array($decoded) && ($decoded['schema'] ?? null) === $schema;
    }

