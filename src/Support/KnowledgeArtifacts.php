    /**
     * @param array<string, mixed> $document
     * @param list<FileRecord> $records
     * @return array<string, mixed>
     */
    private function manifest(array $document, array $records): array
    {
        /** @var KnowledgeDocument $document */
        return [
            'schema' => 'phpforge.knowledge-manifest',
            'schema_version' => 1,
            'fingerprint' => $document['fingerprint'],
            'source_graph' => $document['source_graph'],
            'extractors' => $document['extractors'],
            'files' => $records,
        ];
    }

    private function markdown(string $value): string
    {
        return str_replace(["\r", "\n", '|'], ['', ' ', '\\|'], $value);
    }

    /** @return array{manifest:string,analysis:string,report:string,html:string} */
    private function paths(string $knowledgePath): array
    {
        $directory = dirname($knowledgePath);

        return [
            'manifest' => $directory . DIRECTORY_SEPARATOR . 'manifest.json',
            'analysis' => $directory . DIRECTORY_SEPARATOR . 'analysis.json',
            'report' => $directory . DIRECTORY_SEPARATOR . 'GRAPH_REPORT.md',
            'html' => $directory . DIRECTORY_SEPARATOR . 'graph.html',
        ];
    }

    /**
     * @param array<string, mixed> $document
     * @param KnowledgeAnalysis $analysis
     */
    private function report(array $document, array $analysis): string
    {
        /** @var KnowledgeDocument $document */
        $lines = [
            self::REPORT_MARKER,
            '# PHPForge Knowledge Report',
            '',
            sprintf('- Fingerprint: `%s`', $document['fingerprint']),
            sprintf('- Files: %d', $analysis['file_count']),
            sprintf('- Nodes: %d', $analysis['node_count']),
            sprintf('- Edges: %d', $analysis['edge_count']),
            '',
            '## File coverage',
            '',
            '| Category | Files |',
            '| --- | ---: |',
        ];

        foreach ($document['files'] as $category => $files) {
            $lines[] = sprintf('| %s | %d |', str_replace('_', '-', $category), count($files));
        }

        $lines = [...$lines, '', '## Languages', '', '| Language | Files |', '| --- | ---: |'];

        foreach ($analysis['languages'] as $language => $count) {
            $lines[] = sprintf('| %s | %d |', $this->markdown($language), $count);
        }

        $lines = [...$lines, '', '## Relationships', '', '| Relation | Edges |', '| --- | ---: |'];

        foreach ($analysis['relationships'] as $relation => $count) {
            $lines[] = sprintf('| %s | %d |', $this->markdown($relation), $count);
        }

        $health = $analysis['graph_health'];
        $communityHubs = array_values(array_filter(
            $analysis['communities'],
            static fn(array $community): bool => $community['file_count'] > 1
                || ($community['node_count'] >= 5 && $community['external_edges'] > 0),
        ));
        $thinCommunities = count($analysis['communities']) - count($communityHubs);
        $lines = [
            ...$lines,
            '',
            '## Graph health',
            '',
            sprintf('- Connected components: %d', $health['connected_components']),
            sprintf('- Isolated nodes: %d', $health['isolated_nodes']),
            sprintf('- Self loops: %d', $health['self_loops']),
            sprintf('- Dangling edges: %d', $health['dangling_edges']),
            sprintf('- Density: %.8f', $health['density']),
            '',
            sprintf('## Community Hubs (%d)', count($communityHubs)),
            '',
            sprintf('%d thin standalone communities are retained in `analysis.json` and the HTML explorer but omitted here.', $thinCommunities),
            '',
            '| ID | Community | Nodes | Files | Cohesion | Internal / external edges |',
            '| ---: | --- | ---: | ---: | ---: | ---: |',
        ];

        foreach ($communityHubs as $community) {
            $lines[] = sprintf(
                '| %d | %s | %d | %d | %.3f | %d / %d |',
                $community['id'],
                $this->markdown($community['label']),
                $community['node_count'],
                $community['file_count'],
                $community['cohesion'],
                $community['internal_edges'],
                $community['external_edges'],
            );
        }

        $lines = [...$lines, '', '## God Nodes', '', '| Degree | Communities | Type | Name | File |', '| ---: | ---: | --- | --- | --- |'];

        foreach ($analysis['god_nodes'] as $node) {
            $lines[] = sprintf(
                '| %d | %d | %s | `%s` | %s |',
                $node['degree'],
                $node['communities_reached'],
                $this->markdown($node['type']),
                str_replace('`', '\\`', $this->markdown($node['name'])),
                $this->markdown($node['file']),
            );
        }

        $lines = [...$lines, '', '## Surprising Connections', ''];

        if ($analysis['surprising_connections'] === []) {
            $lines[] = 'No extracted cross-community connections were found.';
        } else {
            foreach ($analysis['surprising_connections'] as $connection) {
                $lines[] = sprintf(
                    '- `%s` → `%s` (%s, %s at %s:%d) — %s',
                    str_replace('`', '\\`', $this->markdown($connection['source_name'])),
                    str_replace('`', '\\`', $this->markdown($connection['target_name'])),
                    $this->markdown($connection['relation']),
                    strtoupper($this->markdown($connection['certainty'])),
                    $this->markdown($connection['file']),
                    $connection['line'],
                    $this->markdown($connection['why']),
                );
            }
        }

        $lines = [...$lines, '', '## Suggested Questions', ''];

        foreach ($analysis['suggested_questions'] as $question) {
            $lines[] = sprintf('- %s — %s', $this->markdown($question['question']), $this->markdown($question['why']));
        }

        $lines[] = '';
        $lines[] = 'Communities, god nodes, bridges and questions are deterministic analysis of extracted relationships. Optional AI explanations remain inferred and are not written into this report.';
        $lines[] = '';

        return implode(PHP_EOL, $lines);
    }

    private function write(string $path, string $contents): void
    {
        $temporary = tempnam(dirname($path), '.phpforge-artifact-');

        if (!is_string($temporary)) {
            throw new \RuntimeException(sprintf('Could not create a temporary artifact in: %s', dirname($path)));
        }

        try {
            if (file_put_contents($temporary, $contents, LOCK_EX) === false || !rename($temporary, $path)) {
                throw new \RuntimeException(sprintf('Could not publish PHPForge artifact: %s', $path));
            }
        } finally {
            if (is_file($temporary)) {
                unlink($temporary);
            }
        }
    }

    /** @param array<string, mixed> $document */
    private function writeJson(string $path, array $document): void
    {
        $this->write($path, json_encode($document, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . PHP_EOL);
    }
}
